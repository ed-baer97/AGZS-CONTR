def facts() -> list[dict[str, str]]:
    titles = dict(GROUPS)
    return [
        {
            "group": item.group,
            "group_title": titles[item.group],
            "title": item.title,
            "detail": item.detail,
            "journal": item.journal,
        }
        for item in FACTS
    ]


